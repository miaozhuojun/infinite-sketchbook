// 多音字：配音模型按最常见的读音念，结构助词常念错（用户听 E02 v5：「细细地讲」的「地」念成了 dì，应念 de）。
// 回转识别听不出来：识别器按意思写回「细细地」，拼音库也把这里的「地」标成 dì。所以在旁白稿里直接写成不会念错的同音字，
// 字幕和画面上照旧写原字（和「锟仔ai科学」念「爱」一样）。这里只收程序能可靠判断的情况，判断不了的不报，不限制怎么写稿。
// 每条：pattern 匹配要改的那一段（g 标志），fix 给出旁白稿里的写法
export const POLYPHONES = [
  // 叠字后面的「地」是状语助词：细细地、慢慢地、悄悄地、一点一点地、一小步一小步地
  { pattern: /([一-鿿])\1地/g, fix: (m) => m.slice(0, -1) + '的', why: '叠字后面的「地」念 de' },
  { pattern: /([一-鿿])\1([一-鿿])\2地/g, fix: (m) => m.slice(0, -1) + '的', why: '叠字后面的「地」念 de' },
  // 「一X一X地」的 X 可以是两个字（E07「一小步一小步地」念成了 dì，原来只认一个字的 X，没拦住）
  { pattern: /一([一-鿿]{1,2})一\1地/g, fix: (m) => m.slice(0, -1) + '的', why: '「一X一X地」的「地」念 de' },
  // 常见的「形容词/副词 + 地 + 动作」
  { pattern: /(认真|仔细|小心|轻轻|使劲|努力|拼命|大声|小声|飞快|高兴|开心|耐心|不停|突然|偷偷|默默|静静|渐渐|紧紧|好好|稳稳|一口气|一步步|一遍遍|自然而然)地/g, fix: (m) => m.slice(0, -1) + '的', why: '状语后面的「地」念 de' },
  // 数量「二 + 量词」口语念「两」：二格、二根、二票（用户 2026-11-16 看 E07 成片：「2格」念成了 èr gé）。
  // 只收几乎总念「两」的量词（二本、二道贩子、二层小楼、二轮车、二块这类固定说法不收，「次」也不收：二次方、二次元）；
  // 前面是第、之、十、百、零、点或别的数字（第二、三分之二、十二、零点二）不算；二分之一、二分法不算
  { pattern: /(?<![第之十百千万亿零点〇一二三四五六七八九\d.])二(?:[格根盏票遍个张样种只位件]|分(?!之|法))/g,
    fix: (m) => '两' + m.slice(1), why: '数量「二 + 量词」口语念「两」' },
  // 当「必须」讲的「得」念 děi，配音常念成 de（E07「得挪到猴年马月」）。dé 开头的词太多（得知、得以、得益、得名……），只认两种位置：
  // 句首或标点后，后面紧跟一个常见动作（得先、得再、得把、得挪、得来……，白名单）；
  // 副词「就还也都总又准非」后面（成就、造就这类词里的「就」不算），后面不是成词的字（得到、得了、得分、得知、得以、得益……）。
  // 名词后面的（「旋钮得一起配」）判断不了，不报，靠写稿自查
  { pattern: /(?<=^|[，。？！；：、])得(?=[先再想让把重从去花等拧挪来走做找换算学试改留跟靠给赶])|(?<![成造迁将])(?:就|还|也|都|总|又|准|非)得(?![到了分出意奖票救逞手体罪失知以益名空天人当寸过很不嘛啦呗咧])/g,
    fix: (m) => m.slice(0, -1) + '要', why: '当「必须」讲的「得」念 děi，配音常念成 de' },
];

// 旁白稿里念错风险的地方：[{ text, say, why, index }]
export function polyphoneIssues(script) {
  const out = [];
  for (const r of POLYPHONES) for (const m of script.matchAll(r.pattern)) out.push({ text: m[0], say: r.fix(m[0]), why: r.why, index: m.index });
  return out.filter((x, i, a) => a.findIndex((y) => y.index === x.index && y.text === x.text) === i);
}
